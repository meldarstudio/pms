export type ReviewKey = (typeof reviewKeys)[number];
export type ReviewText = Record<ReviewKey, string>;

export function reviewText(t: ReturnType<typeof useTranslations>): ReviewText {
  return Object.fromEntries(reviewKeys.map((key) => [key, t(key)])) as ReviewText;
}

export type Say = (key: string, values?: Record<string, string | number>) => string;

export function sayFrom(text: ReviewText): Say {
  return (key, values = {}) => fill(text[key as ReviewKey] ?? key, values);
}
